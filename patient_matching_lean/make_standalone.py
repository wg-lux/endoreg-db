#!/usr/bin/env python3
"""Assemble the modular Lean sources and a transitive axiom audit into one file."""

from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent
MODULES = ("Core", "Privacy", "Workflow", "Counterexamples")
HEADER = """import Std

/-!
Patient matching: checked abstract specification, conditional privacy lemmas,
and impossibility results. Generated by make_standalone.py; edit the modular
sources instead. This is NOT an implementation or security proof of SHA-256,
HMAC, Python serialization, MP-SPDZ, transport, or a production deployment.
Use Lean 4.19.0. All cryptographic and refinement obligations remain explicit.
-/

"""


def assemble() -> tuple[str, list[str]]:
    parts = [HEADER]
    declarations: list[str] = []
    for module in MODULES:
        source = (ROOT / "PatientMatching" / f"{module}.lean").read_text(encoding="utf-8")
        parts.append(f"\n/- ===== Module: {module} ===== -/\n\n")
        parts.append(re.sub(r"^import .+\n", "", source, flags=re.MULTILINE))
        declarations.extend(
            f"PatientMatching.{module}.{name}"
            for name in re.findall(r"^theorem\s+([A-Za-z_][A-Za-z_0-9]*)", source, re.MULTILINE)
        )
    parts.append("\n/- Transitive axiom audit for every named theorem. -/\n")
    parts.extend(f"#print axioms {name}\n" for name in declarations)
    parts.append("""
/- Executable illustrations; the general theorems above are the proofs. -/
#eval PatientMatching.Core.run true true []
#eval PatientMatching.Core.run true true [101]
#eval PatientMatching.Core.run true true [101, 202]
#eval PatientMatching.Core.run false true [101]
#eval PatientMatching.Core.run true false []
#eval PatientMatching.Core.summarizeBits [true, true, false, false]
#eval PatientMatching.Core.summarizeBits [false, false, true, true]
""")
    return "".join(parts), declarations


def main() -> None:
    source, declarations = assemble()
    (ROOT / "PatientMatchingProofs.lean").write_text(source, encoding="utf-8")
    (ROOT / "proof_manifest.json").write_text(
        json.dumps({"lean_version": "4.19.0", "theorems": declarations}, indent=2) + "\n",
        encoding="utf-8",
    )
    print(f"Assembled {len(declarations)} named theorems into PatientMatchingProofs.lean")


if __name__ == "__main__":
    main()
